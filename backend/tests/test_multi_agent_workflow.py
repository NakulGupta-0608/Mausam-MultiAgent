# 4. REVIEW CAPPING & BUDGET STOPPING CONDITION
# ============================================================================

@pytest.mark.asyncio
async def test_orchestrator_review_capping_at_two():
    """Stopping condition: Review attempts capped at maximum limit (2 iterations)."""
    orchestrator = WeatherIntelligencePipeline()

    # Force Critic to always reject to verify capping at 2
    class AlwaysRejectCritic(CriticAgent):
        async def process(self, state, tracer):
            iteration = len(state.critic_reviews) + 1
            from backend.app.schemas.analysis import CriticReview
            review = CriticReview(
                verdict="REJECT",
                critique_score=40,
                data_consistency_passed=False,
                constraints_satisfied=False,
                hallucination_free=True,
                critique_notes="Perpetual contradiction test",
                correction_request="Revise again",
                iteration=iteration,
                timestamp="2026-09-27T00:00:00Z"
            )
            state.critic_reviews.append(review)
            state.current_critic_review = review
            state.active_correction_request = review.correction_request
            return state

    orchestrator.critic = AlwaysRejectCritic()

    req = AnalysisRequest(
        query="Hiking expedition",
        location="Delhi",
        target_date="2026-09-27"
    )

    res = await orchestrator.run(req)

    # Verify review count was strictly capped at 2
    assert res.stopping_condition.reviews_count == 2
    assert res.stopping_condition.stopped_early is True
    assert "capped at maximum limit (2 iterations)" in res.stopping_condition.reason
