# 1. APPROVAL PATH (Happy Path Full Multi-Agent Workflow)
# ============================================================================

@pytest.mark.asyncio
async def test_multi_agent_approval_path():
    """Approval path: All 5 agents execute, Critic validates and issues APPROVE."""
    req = AnalysisRequest(
        query="Can I plan a high altitude mountain trek tomorrow?",
        location="Shimla",
        target_date="2026-09-27"
    )

    response = await pipeline.run(req)

    # 1. Assert Plan generated by PlannerAgent
    assert response.plan is not None
    assert isinstance(response.plan, StructuredPlan)
    assert "Hiking" in response.plan.entities.get("activity_category", "")
    assert len(response.plan.sub_goals) >= 4
    assert "max_rain_probability" in response.plan.constraints

    # 2. Assert Real Telemetry from DataAgent
    assert response.weather is not None
    assert response.weather.source == "open-meteo-live"
    assert response.weather.temp_c is not None

    # 3. Assert Recommendation from RecommendationAgent
    assert len(response.recommendation.options_comparison) >= 2
    assert len(response.recommendation.evidence_citations) >= 3
    assert len(response.recommendation.stated_limitations) >= 3

    # 4. Assert Critic Review produced APPROVE
    assert len(response.critic_reviews) >= 1
    final_review = response.critic_reviews[-1]
    assert final_review.verdict == "APPROVE"
    assert final_review.critique_score >= 70
    assert final_review.hallucination_free is True
    assert final_review.data_consistency_passed is True

    # 5. Assert Audit Trace logs action, reasoning, and duration for all steps
    assert len(response.trace) >= 5
    for step in response.trace:
        assert step.action is not None and len(step.action) > 0
        assert step.reasoning is not None and len(step.reasoning) > 0
        assert step.duration_ms >= 0.0

    # 6. Assert Stopping Condition
    assert response.stopping_condition.reviews_count <= 2
    assert response.stopping_condition.stopped_early is False


