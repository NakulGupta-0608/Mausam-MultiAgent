# 2. REJECTION PATH (Flawed Recommendation Triggers Critic REJECT & Correction)
# ============================================================================

@pytest.mark.asyncio
async def test_critic_rejection_and_correction_cycle():
    """Rejection path: Over-optimistic verdict triggers Critic REJECT with actionable correction."""
    tracer = AgentExecutionTracer()

    # Create mock weather with dangerous rain and wind
    bad_weather = WeatherCondition(
        location=GeoLocation(name="AlpinePass", latitude=32.0, longitude=77.0),
        observed_date="2026-09-27",
        temp_c=6.0,
        feels_like_c=3.0,
        humidity=95,
        wind_kph=38.0,
        wind_direction="NW",
        condition_text="Heavy Rain Showers",
        precipitation_mm=12.0,
        precipitation_prob=85,
        uv_index=3.0,
        forecast_days=[
            DailyForecast(
                date="2026-09-27",
                max_temp_c=8.0,
                min_temp_c=2.0,
                avg_temp_c=5.0,
                condition="Heavy Rain",
                rain_probability=85,
                uv_index=3.0,
                wind_max_kph=38.0
            )
        ],
        source="open-meteo-live"
    )

    state = WorkflowState(
        query="High alpine ridge traverse",
        location_name="AlpinePass",
        target_date="2026-09-27",
        weather=bad_weather,
        outdoor_score=35,
        # Flawed recommendation: claiming "Optimal" despite 85% rain and 38 km/h winds!
        verdict_badge="Optimal",
        headline="Clear skies recommended",
        stated_limitations=["Mountain weather varies"],
    )

    # Initialize plan constraints
    planner = PlannerAgent()
    state = await planner.process(state, tracer)
    # Manually re-assert flawed verdict to test Critic detection
    state.verdict_badge = "Optimal"

    critic = CriticAgent()
    state = await critic.process(state, tracer)

    # Assert Critic caught the contradiction and REJECTED
    first_review = state.current_critic_review
    assert first_review.verdict == "REJECT"
    assert first_review.critique_score < 60
    assert first_review.data_consistency_passed is False
    assert first_review.correction_request is not None
    assert "85%" in first_review.correction_request or "exceeding" in first_review.correction_request

    # Now simulate RecommendationAgent receiving this correction request
    recommender = RecommendationAgent()
    state = await recommender.process(state, tracer)

    # Assert RecommendationAgent revised the verdict upon correction
    assert state.verdict_badge in ["Caution", "Unfavorable"]
    assert "Revised after Critic" in state.comfort_summary or "Caution" in state.verdict_badge

    # Now Critic audits the revised recommendation
    state = await critic.process(state, tracer)
    second_review = state.current_critic_review
    assert second_review.verdict == "APPROVE"
    assert second_review.critique_score > first_review.critique_score


