@pytest.mark.asyncio
async def test_critic_insufficient_data_path():
    """Insufficient data path: Incomplete telemetry triggers NEEDS_MORE_DATA and stops gracefully."""
    tracer = AgentExecutionTracer()

    # Weather with missing critical fields (no forecast days)
    partial_weather = WeatherCondition(
        location=GeoLocation(name="RemoteOutpost", latitude=35.0, longitude=75.0),
        observed_date="2026-09-27",
        temp_c=15.0,
        feels_like_c=14.0,
        humidity=50,
        wind_kph=10.0,
        wind_direction="N",
        condition_text="Clear",
        precipitation_mm=0.0,
        precipitation_prob=10,
        uv_index=4.0,
        forecast_days=[],  # Empty forecast days!
        source="open-meteo-live"
    )

    state = WorkflowState(
        query="Camping trip",
        location_name="RemoteOutpost",
        target_date="2026-09-27",
        weather=partial_weather,
    )

    critic = CriticAgent()
    state = await critic.process(state, tracer)

    review = state.current_critic_review
    assert review.verdict == "NEEDS_MORE_DATA"
    assert review.critique_score <= 30
    assert "Critical meteorological telemetry missing" in review.critique_notes


